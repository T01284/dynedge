#!/usr/bin/env python3
from pathlib import Path

# Avoid directory names that can be mangled by escape handling.
work = Path("<home>/docker_data/fer_mnv3")
work.mkdir(parents=True, exist_ok=True)

# Ensure onnx present
src = Path("<repo>/deploy/ncnn_edge/models/mobilenetv3_small.onnx")
dst = work / "mobilenetv3_small.onnx"
if not dst.exists():
    dst.write_bytes(src.read_bytes())

lines = []
a = lines.append
a("#!/usr/bin/env bash")
a("set -euo pipefail")
a("cd /workspace/fer_mnv3")
a("NAME=mobilenetv3_small")
a('PEG="python3 /root/Vivante_ML_Toolkit_acuity_whl_6.45.8/bin/pegasus.py"')
a("VIV_SDK=/root/Vivante_IDE/VivanteIDE5.8.2/cmdtools")
a("OPT=VIP9000NANOSI_PLUS_PID0X10000016")
a("pwd; ls -la")
a("python3 - <<'PY'")
a("import onnx")
a("m=onnx.load('mobilenetv3_small.onnx')")
a("init={x.name for x in m.graph.initializer}")
a("ins=[]")
a("for i in m.graph.input:")
a("  if i.name in init: continue")
a("  ins.append((i.name,[d.dim_value for d in i.type.tensor_type.shape.dim]))")
a("outs=[(o.name,[d.dim_value for d in o.type.tensor_type.shape.dim]) for o in m.graph.output]")
a("print('inputs', ins)")
a("print('outputs', outs)")
a("PY")
a("echo ==== import ====")
a("$PEG import onnx --model ${NAME}.onnx --output-model ${NAME}.json --output-data ${NAME}.data")
a("echo ==== inputmeta ====")
a("$PEG generate inputmeta --model ${NAME}.json --input-meta-output ${NAME}_inputmeta.yml")
a("python3 - <<'PY'")
a("from pathlib import Path")
a("import struct, zlib, re")
a("p=Path('mobilenetv3_small_inputmeta.yml')")
a("text=p.read_text()")
a("print('RAW META:')")
a("print(text[:2000])")
a("w=h=112")
a("rows=[]")
a("for i in range(h):")
a("  row=bytes([0])")
a("  for j in range(w):")
a("    row += bytes([(i*3+j)%256,(i*5+j*2)%256,(i*7+j*3)%256])")
a("  rows.append(row)")
a("raw=b''.join(rows)")
a("def chunk(t,d):")
a("  return struct.pack('>I',len(d))+t+d+struct.pack('>I',zlib.crc32(t+d)&0xffffffff)")
a("sig=bytes([137,80,78,71,13,10,26,10])")
a("png=sig+chunk(b'IHDR',struct.pack('>IIBBBBB',w,h,8,2,0,0,0))+chunk(b'IDAT',zlib.compress(raw,9))+chunk(b'IEND',b'')")
a("Path('calib0.png').write_bytes(png)")
a("Path('dataset.txt').write_text('\\n'.join(['calib0.png']*16)+'\\n')")
a("if 'dataset.txt' not in text:")
a("  text = text.rstrip()+'\\n\\ndatabases:\\n- path: dataset.txt\\n'")
a("if '123.675' not in text:")
a("  text=re.sub(r'(mean:\\s*\\n(?:-\\s*[^\\n]*\\n){0,3})', 'mean:\\n- 123.675\\n- 116.28\\n- 103.53\\n', text, count=1)")
a("if '0.01712' not in text:")
a("  text=re.sub(r'(scale:\\s*\\n(?:-\\s*[^\\n]*\\n){0,3})', 'scale:\\n- 0.01712\\n- 0.01751\\n- 0.01743\\n', text, count=1)")
a("p.write_text(text)")
a("print('META DONE:')")
a("print(p.read_text()[:2500])")
a("PY")
a("$PEG generate postprocess-file --model ${NAME}.json --postprocess-file-output ${NAME}_postprocess_file.yml || true")
a("$PEG generate postprocess-file --model ${NAME}.json --postprocess-file ${NAME}_postprocess_file.yml || true")
a("test -f ${NAME}_postprocess_file.yml || echo 'type: none' > ${NAME}_postprocess_file.yml")
a("echo ==== quantize ====")
a("$PEG quantize --model ${NAME}.json --model-data ${NAME}.data --device CPU --with-input-meta ${NAME}_inputmeta.yml --quantizer asymmetric_affine --qtype uint8 --iterations 8 --model-quantize ${NAME}_uint8.quantize")
a("echo ==== export ====")
a("mkdir -p wksp")
a("$PEG export ovxlib --model ${NAME}.json --model-data ${NAME}.data --model-quantize ${NAME}_uint8.quantize --with-input-meta ${NAME}_inputmeta.yml --postprocess-file ${NAME}_postprocess_file.yml --dtype quantized --optimize ${OPT} --viv-sdk ${VIV_SDK} --pack-nbg-unify --output-path ./wksp/${NAME}_uint8/${NAME}_uint8")
a("echo ==== artifacts ====")
a("find wksp -type f | head -n 80")
a("find . -name network_binary.nb -ls")

out = work / "convert_inner.sh"
out.write_text("\n".join(lines) + "\n")
out.chmod(0o755)
print("wrote", out)
print("cd line:", out.read_text().splitlines()[2])
